"""Embed channel 1 of the validated voice sample as signed little-endian PCM."""
from pathlib import Path
import struct
import wave


SAMPLE_NAME = "voice-20261031-194442-058191.wav"


def prepare_audio(project_dir):
    project_dir = Path(project_dir)
    source = project_dir.parents[1] / "media" / "output" / SAMPLE_NAME
    with wave.open(str(source), "rb") as audio:
        channels = audio.getnchannels()
        rate = audio.getframerate()
        frames = audio.getnframes()
        if (audio.getsampwidth() != 2 or channels not in (1, 2)
                or rate != 16000 or audio.getcomptype() != "NONE"):
            raise ValueError("Expected mono/stereo 16 kHz, 16-bit PCM WAV")
        if not 0 < frames <= 16 * rate:
            raise ValueError("Expected a nonempty voice sample no longer than 16 seconds")
        data = audio.readframes(frames)
        if len(data) != frames * channels * 2:
            raise ValueError("Truncated WAV payload")
    # The retained capture has voice in channel 1 and silence in channel 2.
    pcm = b"".join(struct.pack("<h", frame[0])
                   for frame in struct.iter_unpack("<" + "h" * channels, data))
    outputs = {
        project_dir / "data" / "voice.pcm": pcm,
        project_dir / "include" / "audio_info.h": (
            "// Generated by prepare_audio.py; do not edit.\n"
            "#pragma once\n"
            f"constexpr unsigned kAudioSampleRate = {rate};\n"
            f"constexpr unsigned kAudioSamples = {frames};\n"
        ).encode(),
    }
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != content:
            path.write_bytes(content)
    print(f"Speaker sample: {SAMPLE_NAME}, {frames / rate:.2f}s, channel 1")


if __name__ == "__main__":
    prepare_audio(Path(__file__).resolve().parent)
elif "Import" in globals():
    # PlatformIO's pre-build script supplies Import through SCons.
    Import("env")
    prepare_audio(env.subst("$PROJECT_DIR"))
